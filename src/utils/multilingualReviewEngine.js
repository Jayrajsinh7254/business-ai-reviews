export const multilingualHistoryRing = [];

/**
 * Synthesizes a unique review for any language and star rating.
 * Guaranteed combinatorial variety exceeds >100,000 unique reviews.
 */
export function synthesizeMultilingualReview({
  language = 'english',
  stars = 5,
  targetMode = 'auto',
  randSeed,
  previousDraft = '',
}) {
  const lang = (language || 'english').toLowerCase().trim();
  if (lang === 'english' || !MATRIX[lang]) {
    return null; // Signals the caller to use the core English synthesizer
  }

  const langPack = MATRIX[lang];
  const starKey = String(Math.max(1, Math.min(5, Math.round(Number(stars) || 5))));
  const bucket = langPack[starKey] || langPack['5'];

  const seed = typeof randSeed === 'number' ? randSeed : Date.now();
  const randA = (seed % 9973) + Math.floor(Math.random() * 10000);
  const randB = Math.floor(Math.random() * 1000000);
  const prevClean = (previousDraft || '').trim().toLowerCase();

  let resolvedMode = targetMode;
  if (!resolvedMode || resolvedMode === 'auto' || resolvedMode === 'random') {
    const roll = Math.random();
    if (roll < 0.30) resolvedMode = 'short';
    else if (roll < 0.70) resolvedMode = 'medium';
    else resolvedMode = 'detailed';
  }

  // For 5-star reviews: 4-part combinatorial matrix (>200,000 permutations)
  if (starKey === '5') {
    const { openers, highlights, qualifiers, closings } = bucket;

    for (let attempt = 0; attempt < 50; attempt++) {
      const oIdx = (randA + attempt * 7) % openers.length;
      const hIdx = (randA + attempt * 11 + 3) % highlights.length;
      const qIdx = (randB + attempt * 13 + 5) % qualifiers.length;
      const cIdx = (randB + attempt * 17 + 9) % closings.length;

      const o = openers[oIdx];
      const h = highlights[hIdx];
      const q = qualifiers[qIdx];
      const c = closings[cIdx];

      let draft = '';
      if (resolvedMode === 'short') {
        draft = o + ' ' + c;
      } else if (resolvedMode === 'medium') {
        const roll = (randA + attempt) % 2;
        draft = roll === 0 ? o + ' ' + h + ' ' + c : h + ' ' + q + ' ' + c;
      } else {
        const flowRoll = (randA + attempt * 3) % 3;
        if (flowRoll === 0) {
          draft = o + ' ' + h + ' ' + q + ' ' + c;
        } else if (flowRoll === 1) {
          draft = h + ' ' + o + ' ' + q + ' ' + c;
        } else {
          draft = o + ' ' + q + ' ' + h + ' ' + c;
        }
      }

      const candClean = draft.trim().toLowerCase();
      if (candClean !== prevClean && !multilingualHistoryRing.includes(candClean)) {
        multilingualHistoryRing.push(candClean);
        if (multilingualHistoryRing.length > 50) multilingualHistoryRing.shift();
        return draft.trim();
      }
    }

    // Default guaranteed combination
    return (openers[0] + ' ' + highlights[0] + ' ' + closings[0]).trim();
  }

  // For 4-star, 3-star reviews (openers * highlights * closings = >1,000 permutations)
  const { openers, highlights, closings } = bucket;
  for (let attempt = 0; attempt < 20; attempt++) {
    const oIdx = (randA + attempt * 5) % openers.length;
    const hIdx = (randA + attempt * 7 + 2) % highlights.length;
    const cIdx = (randB + attempt * 11 + 4) % closings.length;

    let draft = '';
    if (resolvedMode === 'short') {
      draft = openers[oIdx] + ' ' + closings[cIdx];
    } else {
      draft = openers[oIdx] + ' ' + highlights[hIdx] + ' ' + closings[cIdx];
    }

    const candClean = draft.trim().toLowerCase();
    if (candClean !== prevClean && !multilingualHistoryRing.includes(candClean)) {
      multilingualHistoryRing.push(candClean);
      if (multilingualHistoryRing.length > 50) multilingualHistoryRing.shift();
      return draft.trim();
    }
  }

  return (openers[0] + ' ' + highlights[0] + ' ' + closings[0]).trim();
}

